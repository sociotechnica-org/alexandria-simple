"""Validate sorare.jobs.json and emit sorare.jobs.js for the file:// pages.

Browsers block fetch() over file://, so the pages load the data as a script.
Usage: python3 build.py
"""
import json
import os
import sys

import check

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "sorare.jobs.json")
OUT = os.path.join(HERE, "sorare.jobs.js")

if check.main(SRC, os.path.expanduser("~/sorare/library")):
    sys.exit(1)
with open(SRC) as fh:
    data = json.load(fh)
with open(OUT, "w") as fh:
    fh.write("// generated by build.py from sorare.jobs.json; do not edit\n")
    fh.write("window.JOBS_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
print("wrote", os.path.relpath(OUT, HERE))
